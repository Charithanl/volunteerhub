export const getStoredApplications = () => {
  if (typeof window === 'undefined') {
    return defaultApplications;
  }

  try {
    const storedApplications = window.localStorage.getItem(APPLICATIONS_STORAGE_KEY);
    if (!storedApplications) {
      return defaultApplications;
    }

    const parsedApplications = JSON.parse(storedApplications);
    return Array.isArray(parsedApplications) ? parsedApplications : defaultApplications;
  } catch {
    return defaultApplications;
  }
};
